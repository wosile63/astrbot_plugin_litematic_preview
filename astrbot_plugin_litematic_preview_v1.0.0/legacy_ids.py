"""MCEdit / WorldEdit 旧版 .schematic 数字方块 ID -> 现代方块名映射。

数据来源：
  - 基础 ID 表：minecraft-data `data/pc/1.12/blocks.json` 的 `id` -> `name`
    （1.12 是最后一个使用 0~255 数字 ID 的版本）。
  - 名称扁平化（1.13+）：先用 1.12 的 `displayName` 与 minecraft-data
    `data/pc/1.13.2/blocks.json` 的 `displayName` 做唯一匹配得到扁平化名称，
    再对照 `data/pc/1.21.11/blocks.json` 转换到 1.20+ 的现行名称
    （如 grass -> short_grass、grass_path -> dirt_path、sign -> oak_sign）。
  - 变体表（`data` 值 -> 方块名）：在 1.12 `variations[].displayName` 匹配结果基础上
    人工整理/修正，覆盖常用材质/颜色变体（羊毛、染色玻璃、陶瓦、混凝土、地毯、旗帜、
    木板、原木、树叶、台阶、双层台阶、石头变种等）。

已知局限（有意裁剪，700 余行）：
  - 只覆盖原版 1.12 的 0~255 ID；`AddBlocks` 扩展出的 >255 ID 一律返回 legacy:<id>。
  - 不含方块状态（朝向/半砖上下等），渲染端只需按方块名取颜色。
  - 部分仅影响朝向的 data 值未列出，回退到该 ID 的默认名称。

渲染端约定：本模块只返回名称（含 minecraft: 前缀），未知 ID 返回 `legacy:<id>`。
"""

